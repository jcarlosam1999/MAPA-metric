"""
rerun_postpass.py — rerun ONLY the functional post-pass, for chosen members
===========================================================================
run_functional_evaluation() globs every npz in npz_dir and has no member
filter, so calling it directly would also rescore N2 — which is about to be
recomputed anyway with the new guide, and whose 'scf' mode costs one KS-SCF per
functional per geometry. This stages symlinks to the selected members in a temp
dir and points the post-pass at that instead. The npz are never copied or
touched.

It also redirects the benchmark-level summary to a diagnostic file: the real
Functional_Comparison.csv is a benchmark-wide artifact, and a single-member run
would otherwise overwrite it with one row.

The per-system *_Dissociation_Curve.csv IS rewritten in place — that is the
point: every DeltaI column ends up written by ONE config.

    python rerun_postpass.py --only HH_q+0_s0
    python rerun_postpass.py --only HH_q+0_s0 NN_q+0_s0 --modes exact scf
"""

import argparse
import glob
import os
import shutil
import tempfile


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', nargs='+', required=True,
                    help='member names, e.g. HH_q+0_s0')
    ap.add_argument('--modes', nargs='+', default=['exact', 'scf'])
    ap.add_argument('--functionals', nargs='+', default=None,
                    help='default: CFG.functionals_to_eval')
    ap.add_argument('--npz-dir', default='results_grid_data', dest='npz_dir')
    ap.add_argument('--energies-dir', default='results_energies',
                    dest='energies_dir')
    a = ap.parse_args()

    # mutate CFG BEFORE importing functional_eval, per main.py's convention
    from config import CFG
    CFG.functional_density_modes = tuple(a.modes)
    funcs = a.functionals or list(CFG.functionals_to_eval)

    staged = tempfile.mkdtemp(prefix='postpass_npz_')
    n = 0
    try:
        for name in a.only:
            hits = sorted(glob.glob(os.path.join(a.npz_dir, f"{name}_R*.npz")))
            if not hits:
                raise SystemExit(f"no npz for {name!r} in {a.npz_dir!r}")
            for p in hits:
                os.symlink(os.path.abspath(p),
                           os.path.join(staged, os.path.basename(p)))
                n += 1
            print(f"staged {len(hits):3d} geometries for {name}")
        print(f"\nfunctionals : {funcs}")
        print(f"density modes: {tuple(a.modes)}")
        print(f"npz          : {n} files (symlinked, originals untouched)")
        print(f"curve CSVs   : rewritten in place under {a.energies_dir}/")
        print()

        from functional_eval import run_functional_evaluation
        summary = run_functional_evaluation(
            funcs, density_modes=tuple(a.modes), npz_dir=staged,
            energies_dir=a.energies_dir,
            out_summary=os.path.join(
                a.energies_dir, 'Functional_Comparison_RERUN.csv'))
        print()
        print(f"done. Summary -> {a.energies_dir}/Functional_Comparison_RERUN.csv")
        print("(the benchmark-wide Functional_Comparison.csv was NOT touched; "
              "it is\n regenerated by main.py over the full set.)")
        print()
        print("NEXT: python check_grid_decimation.py   — every DeltaI column "
              "is now\nwritten by one config, so the peaks it reports are "
              "finally comparable.")
        return summary
    finally:
        shutil.rmtree(staged, ignore_errors=True)


if __name__ == '__main__':
    main()